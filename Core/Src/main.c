static void BME280_Data_Request() {
	if (bme280_data_request == 1)
	{
		HAL_GPIO_WritePin(GPIOB, GPIO_PIN_13, GPIO_PIN_RESET);

		tx_buffer[0] = READ_WEATHER_DATA_COMMAND;
		HAL_SPI_Transmit_DMA(&hspi2, tx_buffer, READ_WEATHER_DATA_TX_SIZE);

		bme280_data_request = 0;
	}

	if (spi_tx_completed == 1)
	{
		memset(tx_buffer, 0, READ_WEATHER_DATA_COMMAND);

		HAL_SPI_Receive_DMA(&hspi2, rx_buffer, READ_WEATHER_DATA_RX_SIZE);

		spi_tx_completed = 0;
	}

	if (spi_rx_completed == 1)
	{
		HAL_GPIO_WritePin(GPIOB, GPIO_PIN_13, GPIO_PIN_SET);

		memcpy(&BME280, rx_buffer, READ_WEATHER_DATA_RX_SIZE);
		memset(rx_buffer, 0, READ_WEATHER_DATA_RX_SIZE);

		spi_rx_completed = 0;
	}
}

static uint8_t BME280_Data_IsValid(BME280_Data_t* sensor_data) {
	if (sensor_data->Pressure < 50) {
		corrupted_data_count++;
		return 0;
	}
	return 1;
}

static void SSD1306_Screen_Update(BME280_Data_t* sensor_data) {
	if (ssd1306_update_screen == 1)
	{
		ssd1306_update_screen = 0;

		if (BME280_Data_IsValid(sensor_data) == 1) {
			ssd1306_SetCursor(5, 5);
			ssd1306_WriteString("Maga loves Kate!", Font_6x8, White);

			sprintf(
				  (char *) message_buffer,
				  "T: %.1fC",
				  sensor_data->Temperature
			);
			ssd1306_SetCursor(5, 20);
			ssd1306_WriteString(message_buffer, Font_6x8, White);

			sprintf(
				  (char *) message_buffer,
				  "RH: %d%%",
				  ((int) sensor_data->Humidity)
			);
			ssd1306_SetCursor(5, 35);
			ssd1306_WriteString(message_buffer, Font_6x8, White);

			sprintf(
				  (char *) message_buffer,
				  "P: %d hPa",
				  ((int) sensor_data->Pressure)
			);
			ssd1306_SetCursor(5, 50);
			ssd1306_WriteString(message_buffer, Font_6x8, White);

			ssd1306_UpdateScreen();
		}
	}
}

